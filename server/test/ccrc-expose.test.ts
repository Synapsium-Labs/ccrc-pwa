describe('ccrc expose duckdns', () => {
  it('REFUSES a piped stdin — under `curl … | bash`, stdin is the installer', () => {
    // The mutation this pins: delete the `[ -t 0 ]` guard and the verb will
    // happily read a line of shell as this box's DuckDNS token.
    const home = box('ccrc-expose-piped-');
    const r = runPiped(home, ['expose', 'duckdns'], `${SUB}\n${TOKEN}\n`);
    expect(r.code).toBe(1);
    expect(r.stderr).toMatch(/^ccrc: stdin is not a terminal/m);
    expect(r.stderr).toMatch(/curl … \| bash/);
    expect(ccrcDirEntries(home)).toEqual([]);
  });

  it('writes exposure.env (0600) and the Caddyfile (0644), exactly', async () => {
    const home = box('ccrc-expose-duck-ok-');
    const r = await runExposeTty(home, ['duckdns'], [SUB, TOKEN, '']);
    expect(r.code, r.stdout).toBe(0);
    expect(bytesAt(exposurePath(home))).toBe(duckdnsEnv(SUB, TOKEN));
    expect(mode(exposurePath(home)), 'exposure.env holds a token and must be 0600').toBe(0o600);
    expect(bytesAt(caddyfilePath(home))).toBe(caddyfile(HOST, 7788));
    expect(mode(caddyfilePath(home))).toBe(0o644);
    // …and nothing else was left in ~/.ccrc — no temp file survived the mv.
    expect(ccrcDirEntries(home)).toEqual(['Caddyfile', 'exposure.env']);
  });

  it('never echoes and never prints the token — it reaches the FILE and nothing else', async () => {
    // `read -rs` at the prompt, and no line of the transcript ever carries the
    // value. The mutation this pins: drop `-s` (or echo the token back) and
    // the pty transcript contains it.
    const home = box('ccrc-expose-duck-quiet-');
    const r = await runExposeTty(home, ['duckdns'], [SUB, TOKEN, '']);
    expect(r.code, r.stdout).toBe(0);
    expect(r.stdout).not.toContain(TOKEN);
    expect(readFileSync(exposurePath(home), 'utf8')).toContain(TOKEN);
  });

  it('prints the sudo ceremony — exactly three steps, and sudo appears ONLY inside them', async () => {
    // The `_inst_linger` doctrine, verb-sized: ccrc never runs sudo; it prints
    // the exact commands and the operator runs them. The grep shape is the
    // same: every line carrying `sudo` must be a numbered remedy line.
    const home = box('ccrc-expose-duck-ceremony-');
    const r = await runExposeTty(home, ['duckdns'], [SUB, TOKEN, '']);
    expect(r.code, r.stdout).toBe(0);
    expect(r.stdout).toMatch(/1\. install caddy/);
    expect(r.stdout).toMatch(/2\. sudo install -m 0644 .*Caddyfile \/etc\/caddy\/Caddyfile/);
    expect(r.stdout).toMatch(/3\. sudo systemctl enable --now caddy/);
    // D-165. This assertion used to REQUIRE the symlink form — the ceremony
    // shipped it for a month and it cannot work: caddy runs as its own user
    // and `$HOME`/`$HOME/.ccrc` are 750/700 (the 700 is ccrc's own doing), so
    // the link resolves to a file caddy may not read and it fails to load
    // with a permission error nowhere near this instruction. Inverted into a
    // guard: printing a symlink here again is the defect.
    expect(r.stdout, 'the symlink ceremony is unreachable by the caddy user')
      .not.toMatch(/ln -s/);
    expect(r.stdout).not.toMatch(/^expose: {3}4\./m);
    for (const line of r.stdout.split(/\r?\n/).filter((l) => l.includes('sudo'))) {
      expect(line, 'sudo outside the printed remedy').toMatch(/^expose: {3}[23]\. sudo /);
    }
  });

  it('lands degraded-style: names the port-forward prerequisite and the ccrc restart', async () => {
    const home = box('ccrc-expose-duck-landing-');
    const r = await runExposeTty(home, ['duckdns'], [SUB, TOKEN, '']);
    expect(r.code, r.stdout).toBe(0);
    expect(r.stdout).toMatch(/forward ports 80 and 443/);
    // The remedy names a command THIS box has — `systemctl --user restart` on
    // macOS is a second dead end printed at the moment somebody is already
    // following instructions. What is pinned is that the restart is named.
    expect(r.stdout).toMatch(process.platform === 'darwin'
      ? /launchctl kickstart -k gui\/\d+\/app\.ccrc\.ccrc/
      : /systemctl --user restart ccrc\.service/);
  });

  it('reads CCRC_PORT from ccrc.env for the Caddyfile — 7788 is the default, not a constant', async () => {
    const home = box('ccrc-expose-duck-port-');
    mkdirSync(join(home, '.ccrc'), { recursive: true });
    writeFileSync(envFilePath(home), 'CCRC_PORT=9999\n');
    const r = await runExposeTty(home, ['duckdns'], [SUB, TOKEN, '']);
    expect(r.code, r.stdout).toBe(0);
    expect(bytesAt(caddyfilePath(home))).toBe(caddyfile(HOST, 9999));
  });

  it('refuses a subdomain that is not one bare label, and writes nothing', async () => {
    const home = box('ccrc-expose-duck-badsub-');
    const r = await runExposeTty(home, ['duckdns'], ['my.box']);
    expect(r.code).toBe(1);
    expect(r.stdout).toMatch(/not a bare DuckDNS subdomain/);
    expect(ccrcDirEntries(home)).toEqual([]);
  });

  it('is idempotent: a second run with the same answers is byte-identical', async () => {
    const home = box('ccrc-expose-duck-idem-');
    expect((await runExposeTty(home, ['duckdns'], [SUB, TOKEN, ''])).code).toBe(0);
    const envBefore = bytesAt(exposurePath(home));
    const caddyBefore = bytesAt(caddyfilePath(home));
    const r = await runExposeTty(home, ['duckdns'], [SUB, TOKEN, '']);
    expect(r.code, r.stdout).toBe(0);
    expect(bytesAt(exposurePath(home))).toBe(envBefore);
    expect(bytesAt(caddyfilePath(home))).toBe(caddyBefore);
  });

  it('re-running with NEW answers rewrites both files — the REGENERATE class', async () => {
    const home = box('ccrc-expose-duck-rerun-');
    expect((await runExposeTty(home, ['duckdns'], [SUB, TOKEN, ''])).code).toBe(0);
    const r = await runExposeTty(home, ['duckdns'], ['otherbox', 'other-token-1a2b3c', '']);
    expect(r.code, r.stdout).toBe(0);
    expect(bytesAt(exposurePath(home))).toBe(duckdnsEnv('otherbox', 'other-token-1a2b3c'));
    expect(bytesAt(caddyfilePath(home))).toBe(caddyfile('otherbox.duckdns.org', 7788));
  });
});

// ── the shadow refusal (spec D3) ──────────────────────────────────────────

describe('ccrc expose: the shadow refusal', () => {
  // The 3a hand-edit path: an operator who set CCRC_ORIGIN/CCRC_RP_ID in
  // ccrc.env directly. The server unit reads exposure.env SECOND, so a key in
  // both files is silently won by this verb's — the exact overloaded-seam
  // shape the codebase bans. The verb refuses, names both files and which
  // would win, and writes NOTHING. Mutation: delete the refusal → red here.
  for (const key of ['CCRC_ORIGIN', 'CCRC_RP_ID'] as const) {
    it(`refuses when ccrc.env already sets ${key}, naming both files and the winner`, () => {
      const home = box(`ccrc-expose-shadow-${key.toLowerCase()}-`);
      mkdirSync(join(home, '.ccrc'), { recursive: true });
      writeFileSync(envFilePath(home),
        key === 'CCRC_ORIGIN' ? 'CCRC_ORIGIN=https://old.example.com\n' : 'CCRC_RP_ID=old.example.com\n');
      const r = runPiped(home, ['expose', 'duckdns'], `${SUB}\n${TOKEN}\n`);
      expect(r.code).toBe(1);
      expect(r.stderr).toContain(key);
      expect(r.stderr).toContain(envFilePath(home));
      expect(r.stderr).toContain(exposurePath(home));
      expect(r.stderr).toMatch(/wins|would win/);
      expect(existsSync(exposurePath(home))).toBe(false);
      expect(existsSync(caddyfilePath(home))).toBe(false);
    });
  }

  it('a bare KEY= line in ccrc.env is NOT a shadow — empty is unset, the || rule', async () => {
    // `config.ts` reads both keys with `||`, so a bare `CCRC_ORIGIN=` line is
    // an unset key to the server — and must be one to this refusal too, or the
    // verb refuses over a line that decides nothing.
    const home = box('ccrc-expose-shadow-empty-');
    mkdirSync(join(home, '.ccrc'), { recursive: true });
    writeFileSync(envFilePath(home), 'CCRC_ORIGIN=\nCCRC_RP_ID=\n');
    const r = await runExposeTty(home, ['duckdns'], [SUB, TOKEN, '']);
    expect(r.code, r.stdout).toBe(0);
    expect(bytesAt(exposurePath(home))).toBe(duckdnsEnv(SUB, TOKEN));
  });
});


const ccrcIn = (home: string): string => join(home, 'ccrc', 'ccd', 'ccrc');
const exposurePath = (home: string): string => join(home, '.ccrc', 'exposure.env');
const caddyfilePath = (home: string): string => join(home, '.ccrc', 'Caddyfile');
const envFilePath = (home: string): string => join(home, '.ccrc', 'ccrc.env');

/** The exact bytes the duckdns arm writes — asserted whole, because the file
 *  is an EnvironmentFile the server unit sources and a stray character is a
 *  key systemd never sets. */
const duckdnsEnv = (sub: string, token: string, bind = ''): string => [
  "# ccrc exposure config — regenerated by 'ccrc expose'; delete it to go dark.",
  `CCRC_ORIGIN=https://${sub}.duckdns.org`,
  `CCRC_RP_ID=${sub}.duckdns.org`,
  'CCRC_AUTH=on',
  ...(bind ? [`CCRC_CADDY_BIND=${bind}`] : []),
  'CCRC_DDNS_PROVIDER=duckdns',
  `CCRC_DDNS_DOMAIN=${sub}.duckdns.org`,
  `CCRC_DDNS_TOKEN=${token}`,
].join('\n') + '\n';

const byoEnv = (origin: string, rpid: string, bind = ''): string => [
  "# ccrc exposure config — regenerated by 'ccrc expose'; delete it to go dark.",
  `CCRC_ORIGIN=${origin}`,
  `CCRC_RP_ID=${rpid}`,
  'CCRC_AUTH=on',
  ...(bind ? [`CCRC_CADDY_BIND=${bind}`] : []),
].join('\n') + '\n';

/** The ip arm's file (stage 5, S10): NO CCRC_RP_ID — an rpId must be a domain
 *  (webauthn.ts refuses an address literal), so the key is omitted, never
 *  written empty — plus the mode and the measured address, so doctor and a
 *  re-run judge the same box the verb did. */
const ipEnv = (addr: string, bind = ''): string => [
  "# ccrc exposure config — regenerated by 'ccrc expose'; delete it to go dark.",
  `CCRC_ORIGIN=https://${addr}`,
  'CCRC_AUTH=on',
  'CCRC_EXPOSE_MODE=ip',
  `CCRC_EXPOSE_ADDR=${addr}`,
  ...(bind ? [`CCRC_CADDY_BIND=${bind}`] : []),
].join('\n') + '\n';

/** The Caddyfile is exactly this (spec D1): stock Caddy automatic HTTPS does
 *  everything else. No TLS directives, no plugin syntax. The optional `bind`
 *  (D-163) is the ONE line an operator used to have to add by hand — and lose
 *  to the next regeneration. */
const caddyfile = (host: string, port: number, bind = ''): string =>
  `${host} {\n${bind ? `    bind ${bind}\n` : ''}    reverse_proxy 127.0.0.1:${port}\n}\n`;

/** The ip arm's Caddyfile (spec §7): the scheme stated, `tls internal` saying
 *  who signs — caddy's own CA, no ACME, nothing leaves the box. */
const ipCaddyfile = (addr: string, port: number, bind = ''): string =>
  `https://${addr} {\n${bind ? `    bind ${bind}\n` : ''}    tls internal\n    reverse_proxy 127.0.0.1:${port}\n}\n`;

/** A box with the tree `ccrc expose` needs and nothing in `~/.ccrc` yet. The
 *  tree carries `deploy/systemd/` too (a symlink to the repo's): Task 3's
 *  duckdns arm installs the ddns unit TEMPLATES out of the tree it runs from
 *  (`_inst_enable`'s `$CCRC_HERE/..` idiom), and a fixture tree without them
 *  would red every arm on "is this a complete ccrc tree?". */
function box(prefix: string): string {
  const home = mkTmp(prefix);
  const ccd = join(home, 'ccrc', 'ccd');
  mkdirSync(ccd, { recursive: true });
  symlinkSync(CCRC_SRC, join(ccd, 'ccrc'));
  mkdirSync(join(home, 'ccrc', 'deploy'), { recursive: true });
  symlinkSync(join(REPO, 'deploy', 'systemd'), join(home, 'ccrc', 'deploy', 'systemd'));
  return home;
}

/** `systemctlOk`: replace the poison with a stub that RECORDS argv (one line
 *  per call, to `$HOME/systemctl-argv`) and succeeds — the happy-path shape of
 *  a box with a session bus. The default stays the poison: exit 97 IS a test —
 *  the degraded arm — and containment besides. */
function env(home: string, opts: { systemctlOk?: boolean; launchctlOk?: boolean } = {}): NodeJS.ProcessEnv {
  const e = ghContainedEnv(home, { ...process.env, HOME: home });
  // curl and systemctl are poisoned the way ccrc-cli.test.ts poisons them —
  // Task 3's duckdns arm runs `systemctl --user`, and containment each test
  // has to remember is containment that goes missing.
  const poison = (name: string, says: string): void =>
    writeFileSync(join(home, '.local', 'bin', name),
      `#!/bin/sh\nprintf '%s\\n' "$*" >> "$HOME/${name}-poison"\n`
      + `echo "${says}" >&2\nexit 97\n`, { mode: 0o755 });
  poison('curl', 'ccrc tests must never reach a real server');
  if (opts.systemctlOk) {
    writeFileSync(join(home, '.local', 'bin', 'systemctl'),
      '#!/bin/sh\nprintf \'%s\\n\' "$*" >> "$HOME/systemctl-argv"\nexit 0\n', { mode: 0o755 });
  } else {
    poison('systemctl', 'ccrc tests must never touch this box\'s real systemd');
  }
  // launchctl needs no poison: without a stub on PATH, the platform layer's
  // own sandbox-HOME guard refuses the call before any binary runs (that is
  // itself a tested property, macos-platform.test.ts). `launchctlOk` is the
  // Darwin twin of `systemctlOk` — a recorder for the argv-order pins.
  if (opts.launchctlOk) {
    writeFileSync(join(home, '.local', 'bin', 'launchctl'),
      '#!/bin/sh\nprintf \'%s\\n\' "$*" >> "$HOME/launchctl-argv"\nexit 0\n', { mode: 0o755 });
  }
  for (const k of ['CCRC_ADDR', 'CCRC_HEALTH_TIMEOUT', 'CCRC_DOCTOR_GH_TIMEOUT']) delete e[k];
  return e;
}

/** `hostname -I` answers the given line — the ip arm's ONE measurement. The
 *  real binary would answer this box's real addresses: a live value in a
 *  fixture, and a different one on every runner. `null` = the flag fails
 *  (a box whose hostname has no -I, or none at all — the same emptiness). */
function stubHostname(home: string, line: string | null): void {
  mkdirSync(join(home, '.local', 'bin'), { recursive: true });
  writeFileSync(join(home, '.local', 'bin', 'hostname'),
    line === null
      ? '#!/bin/sh\nexit 1\n'
      : `#!/bin/sh\nif [ "$1" = "-I" ]; then printf '%s\\n' "${line}"; exit 0; fi\nexit 1\n`,
    { mode: 0o755 });
}

interface Result { code: number; stdout: string; stderr: string }

/** `ccrc <args>` with stdin NOT a terminal — the shape the tty refusal exists
 *  for, and (with `''`) the shape of every non-interactive invocation. */
function runPiped(home: string, args: string[], stdin = ''): Result {
  const r = spawnSync(BASH, [ccrcIn(home), ...args],
    { env: env(home), encoding: 'utf8', input: stdin });
  return { code: r.status ?? -1, stdout: r.stdout ?? '', stderr: r.stderr ?? '' };
}

/** The four prompt heads the verb can print; one entry is sent per prompt SEEN
 *  (ccrc-passwd.test.ts's `runPasswdTty` synchronisation, generalised). */
const PROMPTS = /(DuckDNS subdomain|DuckDNS token|Public origin|Passkey rp id|Address for caddy to bind)/g;

/** `ccrc expose <args>` on a REAL terminal, typing `entries` at the prompts.
 *  A pty because `[ -t 0 ]` and `read -rs` are two of the things this verb IS:
 *  without a terminal the only reachable branch is the refusal. */
function runExposeTty(
  home: string, args: string[], entries: string[],
  opts: { systemctlOk?: boolean; launchctlOk?: boolean } = {},
): Promise<Result> {
  return new Promise((resolve) => {
    const p = pty.spawn(BASH, [ccrcIn(home), 'expose', ...args], {
      name: 'xterm-color', cols: 200, rows: 40, cwd: home,
      env: env(home, opts) as Record<string, string>,
    });
    let out = '';
    let sent = 0;
    let done = false;
    const finish = (code: number): void => {
      if (done) return;
      done = true;
      clearTimeout(timer);
      resolve({ code, stdout: out, stderr: '' });   // a pty merges the two streams
    };
    const timer = setTimeout(() => { p.kill(); finish(-1); }, 20_000);
    p.onData((d) => {
      out += d;
      const prompts = (out.match(PROMPTS) ?? []).length;
      while (sent < prompts && sent < entries.length) p.write(`${entries[sent++]}\r`);
    });
    p.onExit(({ exitCode }) => finish(exitCode));
  });
}

/** The file's exact bytes, or `null` when there is none. */
const bytesAt = (p: string): string | null => (existsSync(p) ? readFileSync(p, 'utf8') : null);

/** Everything in `~/.ccrc` — the assertion that a refusal left no temp file
 *  behind either. An `exposure.env.tmp.<pid>` holding a live token is not a
 *  leak of nothing. */
const ccrcDirEntries = (home: string): string[] => {
  const d = join(home, '.ccrc');
  return existsSync(d) ? readdirSync(d).sort() : [];
};

const mode = (p: string): number => statSync(p).mode & 0o777;


// Icon vendoring — writes `ui/src/icons/lucide.ts` from a local lucide-static (D-5100).
//
// Run: node ui/design/make-icons.mjs --from <lucide-static>/icons
//
// WHY VENDORED NODES AND NOT `lucide-react`. The package would be a new
// dependency (spec §12 O5) and a fourth React-calling package for
// `pwa/vite.config.ts`'s dedupe lists. Seven icons are a few hundred bytes of
// geometry; the data is copied, with its ISC licence beside it
// (`ui/src/icons/LICENSE.lucide`) and the version in the generated header.
//
// NEVER RUN IN CI. It needs a lucide-static checkout, which is not a dependency
// (fetch one with `npm pack lucide-static` into a scratch directory and pass its
// `icons/` directory). The output is committed; `pwa/test/icon.test.tsx` checks
// it, not this script.
//
// WHAT IT REFUSES. A tag outside the closed set or an attr that is not
// geometric fails the run, rather than being written for the test to catch.
// `Icon` sets the presentation attrs (stroke, caps, joins) itself, so the nodes
// carry geometry and nothing else.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', 'src', 'icons', 'lucide.ts');

/** The icons in use. Add a name here, re-run, and commit both files. */
const NAMES = [
  'bell',
  'bell-off',
  'file-text',
  'folder-code',
  'hand',
  'key-round',
  'mail',
  'settings',
];

const TAGS = new Set(['path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse']);
const ATTRS = new Set(['d', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'x1', 'y1', 'x2', 'y2', 'width', 'height', 'points']);

function arg(flag) {
  const i = process.argv.indexOf(flag);
  return i === -1 ? undefined : process.argv[i + 1];
}

const from = arg('--from');
if (from === undefined) {
  console.error('usage: node ui/design/make-icons.mjs --from <lucide-static>/icons');
  process.exit(2);
}

let version;
const icons = {};
for (const name of NAMES) {
  const svg = readFileSync(path.join(from, `${name}.svg`), 'utf8');
  const v = /@license lucide-static v(\d+\.\d+\.\d+)/.exec(svg)?.[1];
  if (v === undefined) throw new Error(`${name}.svg: no lucide-static version in its licence comment`);
  if (version !== undefined && v !== version) throw new Error(`${name}.svg is ${v}, the others ${version}`);
  version = v;
  // The children between <svg ...> and </svg>, taken whole rather than by
  // stripping comments: the licence comment sits before <svg>, and anything
  // inside the body the node parser does not read (a comment included) fails
  // the leftover check below.
  const body = /<svg\b[^>]*>([\s\S]*)<\/svg>/.exec(svg)?.[1];
  if (body === undefined) throw new Error(`${name}.svg: no <svg> element`);
  const nodes = [];
  for (const m of body.matchAll(/<([a-z]+)\s([^>]*?)\/>/g)) {
    const [, tag, rest] = m;
    if (!TAGS.has(tag)) throw new Error(`${name}.svg: <${tag}> is outside the closed set`);
    const attrs = {};
    for (const a of rest.matchAll(/([a-zA-Z0-9-]+)="([^"]*)"/g)) {
      // A DOT. lucide fills a tiny circle (`key-round`'s r=".5") with
      // currentColor. Icon's thinnest stroke is 1.5, whose round half-width
      // 0.75 already covers any disc of r <= 0.75, so the fill draws nothing the
      // stroke does not: it is dropped, and a bigger filled shape still fails.
      if (a[1] === 'fill' && a[2] === 'currentColor' && tag === 'circle' && Number(/\br="([^"]*)"/.exec(rest)?.[1]) <= 0.75) continue;
      if (!ATTRS.has(a[1])) throw new Error(`${name}.svg: <${tag} ${a[1]}> is not geometric`);
      attrs[a[1]] = a[2];
    }
    nodes.push([tag, attrs]);
  }
  if (body.replace(/<([a-z]+)\s([^>]*?)\/>/g, '').trim() !== '') throw new Error(`${name}.svg: content the parser did not read`);
  if (nodes.length === 0) throw new Error(`${name}.svg: no nodes`);
  icons[name] = nodes;
}

const lines = [
  `// GENERATED by ui/design/make-icons.mjs from lucide-static ${version} (ISC, ./LICENSE.lucide).`,
  '// Do not edit by hand: add the name to the script\'s list and re-run it.',
  '',
  `export const LUCIDE_VERSION = '${version}';`,
  '',
  '/** One SVG child: a tag from a closed set, and geometric attrs only. */',
  "export type IconNode = readonly ['path' | 'circle' | 'rect' | 'line' | 'polyline' | 'polygon' | 'ellipse', Readonly<Record<string, string>>];",
  '',
  '/** The vendored icons. A key is bare wherever it can be, and `IconName` is',
  ' *  derived from the keys rather than spelled as a union of quoted names: a',
  ' *  name in single quotes anywhere in ui/src reads to the boundary census',
  ' *  (design-system-boundary.test.ts) as a class this package emits, and the',
  ' *  bell icon shares its name with the app\u2019s own bell rule. */',
  'export const ICONS = {',
  ...NAMES.flatMap((n) => [
    `  ${/^[a-z][a-z0-9]*$/.test(n) ? n : `'${n}'`}: [`,
    ...icons[n].map(([tag, attrs]) => `    ['${tag}', ${JSON.stringify(attrs).replace(/"([a-z0-9]+)":/g, '$1: ').replace(/,(?=[a-z0-9]+: )/g, ', ').replace(/^\{/, '{ ').replace(/\}$/, ' }').replace(/"/g, "'")}],`),
    '  ],',
  ]),
  '} as const satisfies Readonly<Record<string, readonly IconNode[]>>;',
  '',
  'export type IconName = keyof typeof ICONS;',
  '',
];
writeFileSync(OUT, lines.join('\n'));
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${NAMES.length} icons from lucide-static ${version}`);
